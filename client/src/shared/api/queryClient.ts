import { QueryClient } from '@tanstack/react-query'

export const queryClient = new QueryClient({
  defaultOptions: {
    queries: {
      // Не считаем данные устаревшими 30 секунд после получения.
      // Важно для карты: при повторном открытии той же области
      // не будет лишнего запроса.
      staleTime: 30_000,

      // Держим неактивные кеши 5 минут.
      // Если пользователь ушёл с карты и вернулся — данные ещё в кеше.
      gcTime: 5 * 60_000,

      // Не рефетчим при фокусе окна — иначе при переключении вкладок
      // карта будет дёргаться.
      refetchOnWindowFocus: false,

      // Не рефетчим при переподключении сети (опционально,
      // но для карты с bounds-запросами это лишняя нагрузка).
      refetchOnReconnect: false,

      // При ошибке не спамим повторами — пользователь сам решит.
      retry: 1,
    },
    mutations: {
      retry: 0,
    },
  },
})
